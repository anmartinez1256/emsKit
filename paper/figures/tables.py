"""The tables of the current build, written from results/ so that no number is typed twice: Table tab:current
(tab_current.tex) from the table of results/speed_cg29_2026-11-05.txt, Table tab:e2ecg29 (tab_e2e_cg29.tex) from the
tables of results/rfsim_e2e_cg29_2026-11-05.txt, and the speed table of README.md (between its '<!-- BEGIN speed table'
and '<!-- END speed table -->' lines; without them the table is printed). Every value is one of those files' medians
or median paired ratios, as the file rounds it; only the labels, the README's model descriptions and the earlier
runs' times quoted from results/rfsim_e2e_2026-11-03.txt (EARLIER below) are written here. The script stops without
writing anything if a CPU run of the speed file is not identical to stock or the two engines of an end-to-end run stop
at different steps."""
import os, re
H = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(H, "..", "..", "results")
SPEED, E2E = os.path.join(R, "speed_cg29_2026-11-05.txt"), os.path.join(R, "rfsim_e2e_cg29_2026-11-05.txt")
README = os.path.join(H, "..", "..", "README.md")
DESC = {"GCPW line": "GCPW line, conducting sheets, MUR", "SMA launch": "vertical SMA launch, coaxial port, z-PML",
        "notch tutorial": "notch filter tutorial, MSL ports, PML_8 at both x ends",
        "patch tutorial": "patch antenna tutorial, nf2ff", "patch x5": "patch antenna x5", "notch x3": "notch filter x3"}
SETTING = ["4", "8", "auto"]
OUT = {}  # path -> text, written by write() once every check has passed


def write():
    for p, t in OUT.items():
        open(p, "w").write(t)
        print("wrote", os.path.basename(p))


def table(path, col):
    """The rows (lists of cells) of the first '# | ...' table of a results file whose header row has the cell col."""
    tabs, inside = [], False
    for line in open(path):
        if not line.startswith("# | "):
            inside = False
            continue
        f = [x.strip() for x in line.rstrip().rstrip("|")[4:].split("|")]
        if inside:
            tabs[-1][1].append(f)
        else:
            tabs.append((f, []))
            inside = True
    return next(rows for head, rows in tabs if col in head)


def med(s):
    """'1548 [1504-1584]', '286 [282-287] (4)', 'x6.33 [6.28-6.42]', '0.5 [1.3]' -> (median, low, high, extra)."""
    m = re.match(r"^x?([\d.]+) \[([\d.]+)(?:-([\d.]+))?\](?: \((\d+)\))?$", s)
    assert m, s
    return float(m[1]), float(m[2]), float(m[3] or m[2]), m[4] and int(m[4])


def sci(x):
    """9.4e-07 -> '9.4\\times10^{-7}' (LaTeX math)."""
    a, b = f"{x:.1e}".split("e")
    return a + r"\times10^{" + str(int(b)) + "}"


def tsci(x):
    """A difference for the text: '0' or '$9.4\\times10^{-7}$'."""
    return "0" if x == 0 else "$" + sci(x) + "$"


def thin(n):
    """94217 -> '94\\,217'."""
    return f"{n:,}".replace(",", r"\,")


# ---- speed: per model stock best, cg29 CPU 4 / 8 / auto, metal-diamond, three paired ratios, load, rounds
raw = open(SPEED).read()
for c, res in re.findall(r"^r\d+ c(\d) +[\d.]+ MC/s .*%  (\S.*)$", raw, re.M):
    assert c == "6" or res in ("identical", "reference"), f"CPU config c{c}: {res}"
SP = []
for f in table(SPEED, "metal-diamond"):
    m = re.match(r"^(.+) \(([\d.]+) M\)$", f[0])
    st, cpu = med(f[1]), [med(x)[0] for x in f[2:5]]
    SP.append(dict(name=m[1], cells=float(m[2]), stock=st[0], stock_thr=st[3], cpu=cpu,
                   best=max(range(3), key=lambda i: cpu[i]), gpu=med(f[5])[0], r_cpu=med(f[6])[0], r_gpu=med(f[7])[0],
                   r_gc=med(f[8])[0], load=med(f[9]), redo=int(f[10]), rounds=f[11],
                   loaded=int(re.search(r"(\d+) loaded", f[11])[1]) if "loaded" in f[11] else 0,
                   rerun="re-run" in f[11]))
probe = re.search(r"^# Probe differences of the GPU runs.*?: (.*)$", raw, re.M)[1]
gpu_rel = max(float(x) for x in re.findall(r"probes rel ([\d.e+-]+)", probe))
lo, hi = min(r["load"][0] for r in SP), max(r["load"][0] for r in SP)
rerun = [r["name"] for r in SP if r["rerun"]]

tex = ["% Generated by figures/tables.py from results/speed_cg29_2026-11-05.txt; edit the script, not this file.",
       r"\begin{table}[H]\centering\small",
       r"\resizebox{\ifdim\width>\textwidth\textwidth\else\width\fi}{!}{\begin{tabular}{@{}lrrrrrrrr@{}}",
       r"\toprule",
       r" & stock v0.37.0 & \multicolumn{3}{c}{cg29, CPU (multithreaded)} & cg29, GPU & "
       r"\multicolumn{3}{c@{}}{paired ratio} \\",
       r"\cmidrule(lr){2-2}\cmidrule(lr){3-5}\cmidrule(lr){6-6}\cmidrule(l){7-9}",
       r"model (cells) & best (thr) & 4 thr & 8 thr & auto & diamond & CPU / stock & GPU / stock & GPU / CPU \\",
       r"\midrule"]
for r in SP:
    c = [f"{v:.0f}" if i != r["best"] else r"\textbf{" + f"{v:.0f}" + "}" for i, v in enumerate(r["cpu"])]
    cells = f"{r['cells']:.3f}" if r["cells"] < 2 else f"{r['cells']:.2f}"
    tex.append(f"{r['name']} ({cells}" + r"\,M)" + ("$^{a}$" if r["loaded"] else "") +
               f" & {r['stock']:.0f} ({r['stock_thr']}) & " + " & ".join(c) +
               f" & {r['gpu']:.0f} & {r['r_cpu']:.2f} & {r['r_gpu']:.2f} & {r['r_gc']:.2f}" + r" \\")
tex += [r"\bottomrule", r"\end{tabular}}"]
cap = (r"\caption{Snapshot cg29 (patches 0001--0027) against stock v0.37.0 on the six models, \MC, measured on "
       r"2026-11-05 (\code{results/speed\_cg29\_2026-11-05.txt}). One paired interleaved run per model "
       r"(\code{bench/abtest.py}, 4 rounds, the step counts of \code{bench/check.sh}): every round runs stock at 2, 4 "
       r"and 8 threads, cg29's multithreaded engine at 4 and 8 threads and with the automatic thread count, and cg29's "
       r"Metal diamond engine, in turn, once the other processes use at most 1.5 cores and 10\,\% of the GPU, and is "
       r"run again, up to three times, when they rose above that during one of its runs")
if rerun:
    cap += (r"; the " + " and ".join(rerun) + r" row" + ("s come" if len(rerun) > 1 else " comes") +
            r" from a re-run that repeats the single loaded runs instead (\code{--run-redo 3})")
cap += (r". Rates: the median over the rounds; ratios: the median of the per-round ratios. Stock: the best of its "
        r"three thread counts. Bold: cg29's best CPU setting, which the two CPU ratios use. Every CPU run's port probes "
        r"are identical to stock's at 4 threads; the GPU runs differ from them by at most $" + sci(gpu_rel) +
        r"$ relative, because the GPU flushes subnormal numbers (with \code{OPENEMS\_FTZ=1} on the CPU they are "
        r"identical, \code{results/*\_cg29gpu.txt}). The SMA launch on the 1.071\,M-cell mesh of the earlier tables "
        r"(\code{RFSIM\_MIN\_CELL=0.02}); the toolkit's default since 2026-11-04 builds 0.871\,M cells. The other "
        r"processes used a median of " + f"{lo:.1f}--{hi:.1f}" + r" cores per model during the runs kept.")
for r in SP:
    if r["loaded"]:
        cap += (f" $^{{a}}$Measured under load: in {r['loaded']} of the rounds used a run saw the others above the "
                f"limit (median {r['load'][0]:.1f} cores, up to {r['load'][2]:.1f}); its rates are not comparable "
                f"with the other rows.")
tex += [cap + r"}\label{tab:current}", r"\end{table}"]
OUT[os.path.join(H, "tab_current.tex")] = "\n".join(tex) + "\n"

# ---- README speed table
md = ["| model (cells) | stock v0.37.0, MC/s (threads) | fdtdKit CPU, MC/s (threads) | gain | fdtdKit GPU, MC/s | gain "
      "| GPU / CPU |", "|---|---|---|---|---|---|---|"]
for r in SP:
    md.append(f"| {DESC[r['name']]} ({r['cells']:.2f} M){' (loaded, see below)' if r['loaded'] else ''} | "
              f"{r['stock']:.0f} ({r['stock_thr']}) | {r['cpu'][r['best']]:.0f} ({SETTING[r['best']]}) | "
              f"{r['r_cpu']:.2f}x | {r['gpu']:.0f} | {r['r_gpu']:.2f}x | {r['r_gc']:.2f}x |")
note = ("(Snapshot cg29, measured on 2026-11-05 in one paired interleaved run per model, 4 rounds, "
        "`results/speed_cg29_2026-11-05.txt`: stock at 2, 4 and 8 threads, fdtdKit's multithreaded engine at 4 and 8 "
        "threads and with the automatic count, and its Metal diamond engine (`--engine=metal-diamond`), in turn, each "
        "round once the other processes used at most 1.5 cores and 10 % of the GPU, and run again, up to three times, "
        "when a run saw more")
if rerun:
    note += ("; the " + " and ".join(rerun) + " row" + ("s come" if len(rerun) > 1 else " comes") +
             " from a re-run that repeats only the loaded runs (`--run-redo 3`)")
note += (". Rates are medians over the rounds, gains the median of the per-round ratios; stock and fdtdKit CPU at "
         "their best thread count in the run. The CPU runs are identical to stock bit for bit; the GPU runs differ by "
         f"at most {gpu_rel:.1e} relative because the GPU flushes subnormal numbers (identical with `OPENEMS_FTZ=1` on "
         "the CPU). The SMA launch on the 1.071 M-cell mesh of the toolkit's former 0.02 mm floor. MC/s = million Yee "
         "cells updated per second.)")
for r in SP:
    if r["loaded"]:
        note += (f" The {r['name']} ran while other processes loaded the Mac ({r['loaded']} of its rounds had a run "
                 f"above the limit, median {r['load'][0]:.1f} cores): its rates are not comparable with the other rows.")
block = "\n".join(md) + "\n\n" + note + "\n"
txt = open(README).read()
m = re.search(r"(<!-- BEGIN speed table[^\n]*-->\n)(.*?)(<!-- END speed table -->)", txt, re.S)
if m:
    OUT[README] = txt[:m.start(2)] + block + txt[m.end(2):]
else:
    print("README has no speed table markers; the table:\n" + block)

# ---- end to end: cg29 CPU against the Metal diamond engine, the toolkit's defaults and the full runs
if not os.path.exists(E2E):
    write()
    raise SystemExit(f"no {os.path.basename(E2E)} yet: tab_e2e_cg29.tex not written")
CASE = {"GCPW full run": "G_off", "GCPW default run": "G_60h", "SMA full run": "S_off", "SMA default run": "S_60h"}
LAB = {"GCPW full run": "GCPW line, full run", "GCPW default run": "GCPW line, toolkit default",
       "SMA full run": "SMA launch, full run", "SMA default run": "SMA launch, toolkit default"}
# the same boards, settings and steps in results/rfsim_e2e_2026-11-03.txt, FDTD.Run s (one run each on a quiet Mac,
# stock with the toolkit's 4 threads, cg18 with its tuner); the SMA's full run on the 0.871 M mesh was not made there
EARLIER = {"GCPW full run": (94217, "76.5", "13.7"), "GCPW default run": (34300, None, "5.2"),
           "SMA full run": (None, None, None), "SMA default run": (50320, None, "37.4")}
e2e = open(E2E).read()
runs = {}
for f in table(E2E, "engine"):
    if len(f) >= 10 and f[2] in ("cpu", "gpu"):
        ts = [int(x) for x in f[3].split()[0].split("/")]
        assert len(ts) == 1, f"{f[0]} {f[2]}: the rounds stopped at different steps {ts}"
        runs[(f[0], f[2])] = dict(cells=float(f[1].split()[0]), ts=ts[0], run=med(f[4])[0],
                                  ratio=med(f[9])[0] if f[9] else None, load=med(f[7]),
                                  loaded=int(f[10]) if len(f) > 10 and f[10] else 0)
# GPU against the CPU run of the same round: max |dS11| dB (where |S11| > -40 dB; '-' if never), |dS21| dB, dZ0 ohm
dif = table(E2E, "dS11 dB")
assert dif and all(f[7] == "yes" for f in dif), "an end-to-end round stopped at different steps on the two engines"
d11 = max((float(f[2]) for f in dif if f[2] != "-"), default=None)
d21 = max(float(f[3]) for f in dif)
dz0 = max(abs(float(f[5].split()[0])) for f in dif)
def loaded_e2e():
    """The caption's clause on kept runs that stayed loaded through the third redo ('' when there were none)."""
    used = [v for k, v in runs.items() if k[0] in CASE]
    n, tot = sum(v["loaded"] for v in used), sum(len(re.findall(r"^r\d+ " + CASE[k[0]] + r"\s+" + k[1] + " ", e2e, re.M))
                                                for k in runs if k[0] in CASE)
    if not n:
        return ""
    worst = max(v["load"][2] for v in used if v["loaded"]) / 100
    return (f"; in {n} of the {tot} runs kept the others stayed above that through the third redo (at most "
            f"{worst:.1f} cores): the medians include them, and the file gives the medians of the clean runs as well")


e = ["% Generated by figures/tables.py from results/rfsim_e2e_cg29_2026-11-05.txt; edit the script, not this file.",
     r"\begin{table}[H]\centering\small",
     r"\resizebox{\ifdim\width>\textwidth\textwidth\else\width\fi}{!}{\begin{tabular}{@{}lrrrrrrr@{}}",
     r"\toprule",
     r" & & & \multicolumn{3}{c}{cg29, \code{FDTD.Run} wall time} & \multicolumn{2}{c@{}}{2026-11-03, same steps} \\",
     r"\cmidrule(lr){4-6}\cmidrule(l){7-8}",
     r"run & cells & steps & CPU & GPU & CPU / GPU & stock & cg18 \\",
     r"\midrule"]
nr = []
for k in CASE:
    c, g = runs.get((k, "cpu")), runs.get((k, "gpu"))
    if not c or not g:
        continue
    assert c["ts"] == g["ts"], f"{k}: CPU stops at {c['ts']}, GPU at {g['ts']}"
    ts, st, c18 = EARLIER[k]
    assert ts is None or ts == c["ts"], f"{k}: {c['ts']} steps, {ts} in the earlier run"
    nr.append(len(re.findall(r"^r\d+ " + CASE[k] + r"\s+cpu ", e2e, re.M)))
    e.append(f"{LAB[k]} & {c['cells']:.3f}" + r"\,M & " + thin(c["ts"]) + f" & {c['run']:.1f}" + r"\,s & " +
             f"{g['run']:.1f}" + r"\,s & " + f"{g['ratio']:.2f}" + r"$\times$ & " +
             (st + r"\,s" if st else "--") + " & " + (c18 + r"\,s" if c18 else "--") + r" \\")
e += [r"\bottomrule", r"\end{tabular}}"]
e.append(r"\caption{End-to-end runs of the two boards from the author's toolkit with snapshot cg29 on 2026-11-05 "
         r"(\code{results/rfsim\_e2e\_cg29\_2026-11-05.txt}): the multithreaded engine with the automatic thread count "
         r"(CPU) against the Metal diamond engine (GPU), with the toolkit's defaults since 2026-11-04 (SMA mesh floor "
         r"0.05\,mm, 0.871\,M cells; probe end $-60$\,dB with a hold of 0.5 excitation lengths: ``toolkit default'') "
         r"and with the probe end off (``full run'', to \code{max\_time}: GCPW 12\,ns, SMA 10\,ns). Time: wall time of "
         r"\code{FDTD.Run} (operator setup and time stepping), the median over " +
         (f"{min(nr)}--{max(nr)}" if min(nr) != max(nr) else f"{nr[0]}") +
         r" interleaved rounds; each run started once the other processes used at most 1.5 cores and 10\,\% of the "
         r"GPU and was run again, up to three times, when they rose above that during it" + loaded_e2e() +
         r". CPU\,/\,GPU: the median of "
         r"the per-round ratios of the run times. In every round both engines stop at the same step; " +
         (r"their S-parameters and $Z_0$ are the same" if not (d11 or d21 or dz0) else
         r"the GPU's results differ from the CPU's by at most " + (tsci(d11) + r"\,dB in $S_{11}$ (where $|S_{11}|>-40$\,dB), "
                                                  if d11 is not None else "") +
         tsci(d21) + r"\,dB in $S_{21}$ and " + tsci(dz0) + r"\,$\Omega$ in $Z_0$ at the reference frequency, as "
         r"the GPU flushes subnormal numbers (the file gives each round)") + r". The last two columns are "
         r"the runs with the same settings and steps in Table~\ref{tab:e2e} (one run each, stock with the toolkit's 4 "
         r"threads, cg18 with its tuner, on a quiet Mac: the others below one core for 10\,s before each run); the "
         r"SMA's full run on the 0.871\,M mesh was not made there. During the runs here the others used a median of " +
         f"{min(v['load'][0] for v in runs.values()) / 100:.1f}--{max(v['load'][0] for v in runs.values()) / 100:.1f}"
         r" cores per row, so the CPU columns are not a comparison with cg18 (paired, cg29 against cg18: "
         r"Section~\ref{sec:cg29}).}\label{tab:e2ecg29}")
e.append(r"\end{table}")
OUT[os.path.join(H, "tab_e2e_cg29.tex")] = "\n".join(e) + "\n"
write()
